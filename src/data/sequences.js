export const RANK_ORDER = ["U", "G", "F", "E", "D", "C", "B", "A", "S"];

export function getRankSequenceById(id) {
  return SEQUENCES.find((s) => s.id === id) || null;
}
export function getSequencesByRank(rank) {
  return SEQUENCES.filter((s) => s.rank === rank);
}
export function getSequencesForMovement(movementId) {
  return SEQUENCES.filter((s) => s.movements.includes(movementId));
}
export function getSequencesByType(type) {
  return SEQUENCES.filter((s) => s.type === type);
}
export function getSequencesUpToRank(rankId) {
  const idx = RANK_ORDER.indexOf(rankId);
  if (idx === -1) return [];
  const allowed = new Set(RANK_ORDER.slice(0, idx + 1));
  return SEQUENCES.filter((s) => allowed.has(s.rank));
}
