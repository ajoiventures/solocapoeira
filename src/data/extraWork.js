// SCIENCE BASIS (4 sources integrated):
// ─ Zatsiorsky, "Science & Practice of Strength Training": 3 training methods
//     maximal  = 1-3 reps @ ~90-100% 1RM → neural drive, RFD, motor coordination
//     dynamic  = submaximal load at MAXIMUM SPEED → power, velocity, explosiveness
//     repeated = 8-15 reps to/near failure → hypertrophy, recruit high-threshold MUs
//     submaximal = moderate reps, NOT to failure → maintenance, conditioning
// ─ Verkhoshansky & Siff, "Supertraining": Dynamic Correspondence principle
//     Each exercise should match the sport movement in direction, amplitude, and RFD
