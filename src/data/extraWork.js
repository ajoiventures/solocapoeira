// ── Phase-appropriate conditioning pools ─────────────────────────
// Based on Joyce & Lewindon periodization phases
const GPP_CONDITIONING = CONDITIONING_EXTRAS.filter((e) =>
  ["kb_swing_emom", "vest_ginga_10", "cocorinha_hold_ladder", "negativa_flow", "capoeira_interval_ladder"].includes(e.id)
);
const SPP_CONDITIONING = CONDITIONING_EXTRAS.filter((e) =>
  ["short_short_hiit", "au_intervals", "vest_ginga_sprint", "kb_swing_emom", "kb_swing_for_time", "pyramid_swings"].includes(e.id)
);
const PRE_COMP_CONDITIONING = CONDITIONING_EXTRAS.filter((e) =>
  ["moderate_moderate_hiit", "kb_tabata_swing", "vest_burpee_au", "kb_snatch_complex", "kb_complex_circuit", "vest_flow_circuit"].includes(e.id)
);
const COMP_CONDITIONING = CONDITIONING_EXTRAS.filter((e) =>
  ["roda_replication_hiit", "vest_burpee_au", "kb_swing_for_time", "capoeira_interval_ladder", "moderate_moderate_hiit"].includes(e.id)
);

function getConditioningPool(week) {
  if (week <= 12)  return GPP_CONDITIONING.length  ? GPP_CONDITIONING  : CONDITIONING_EXTRAS;
  if (week <= 24)  return SPP_CONDITIONING.length  ? SPP_CONDITIONING  : CONDITIONING_EXTRAS;
  if (week <= 36)  return PRE_COMP_CONDITIONING.length ? PRE_COMP_CONDITIONING : CONDITIONING_EXTRAS;
  return COMP_CONDITIONING.length ? COMP_CONDITIONING : CONDITIONING_EXTRAS;
}

// ── Daily selection — deterministic, rotates every session ────────
// Returns { strength: Ex[], conditioning: Ex[] } — 4 strength + 3 conditioning each day
// Conditioning pool is phase-appropriate based on the current week
export function getDailyExtras(week, dow) {
  const seed = (week * 7 + dow) % 1000;
  const condPool = getConditioningPool(week);

  const pickRotating = (pool, count, offset) => {
    if (!pool.length) return [];
    const start = (seed + offset) % pool.length;
    const rotated = [...pool.slice(start), ...pool.slice(0, start)];
    return rotated.slice(0, count);
  };

  return {
    strength:     pickRotating(STRENGTH_EXTRAS, 4, 0),
    conditioning: pickRotating(condPool, 3, 13),
    core:         pickRotating(CORE_EXTRAS, 2, 31),
    sand:         pickRotating(SAND_EXTRAS, 2, 47),
  };
}
