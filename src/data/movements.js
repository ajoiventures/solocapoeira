const titleFromId = (id = "") =>
  String(id)
    .replace(/[-_]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\b\w/g, (char) => char.toUpperCase()) || "Movement";

const inferTreeFromId = (id = "") => {
  const value = String(id).toLowerCase();
  if (value.includes("ginga") || value.includes("esquiva") || value.includes("negativa") || value.includes("queda")) return "Foundation";
  if (value.includes("au") || value.includes("bananeira") || value.includes("piao")) return "Au";
  if (value.includes("macaco") || value.includes("mola") || value.includes("ponte")) return "Macaco";
  if (value.includes("rins") || value.includes("tesoura") || value.includes("corta") || value.includes("rel")) return "Floor";
  if (value.includes("rasteira") || value.includes("banda") || value.includes("vingativa") || value.includes("arrast")) return "Sweep";
  if (value.includes("chapa") || value.includes("martelo") || value.includes("armada") || value.includes("lua") || value.includes("queixada")) return "Kick";
  if (value.includes("mandinga") || value.includes("malicia") || value.includes("chamada")) return "Mandinga";
  return "Foundation";
};

