const buildMovementInstructions = (movement) => {
  if (Array.isArray(movement.instructions) && movement.instructions.length > 0) {
    return movement.instructions;
  }

  const firstProgression = movement.progressions?.[0] || `mark ${movement.name} slowly`;
  const secondProgression = movement.progressions?.[1] || "add rhythm without adding speed";
  const thirdProgression = movement.progressions?.[2] || "connect the movement to ginga";

  return [
    `Warm up the joints used by ${movement.name}, then rehearse the entry at half speed.`,
    `Drill the base shape: ${firstProgression}.`,
    `Build control with ${secondProgression}, keeping the breath even and the gaze active.`,
    `Integrate it into flow: ${thirdProgression}.`,
    `Finish each set by checking the standard: ${movement.unlockTest || movement.masteryTest}.`,
  ];
};

const normalizeMovementProfile = (movement, requestedId = movement?.id) => {
  if (!requestedId && !movement) return null;

  const base = movement || createFallbackMovementProfile(requestedId);
  const normalized = {
    ...base,
    id: base.id || requestedId,
    name: base.name || titleFromId(requestedId),
    meaning: base.meaning || "Movement profile",
    tree: base.tree || inferTreeFromId(requestedId),
    tier: base.tier || 1,
    category: Array.isArray(base.category) ? base.category : ["movement"],
    prerequisites: Array.isArray(base.prerequisites) ? base.prerequisites : [],
    physicalRequirements: Array.isArray(base.physicalRequirements) ? base.physicalRequirements : [],
    progressions: Array.isArray(base.progressions) ? base.progressions : [],
    commonWeaknesses: Array.isArray(base.commonWeaknesses) ? base.commonWeaknesses : [],
    difficulty: base.difficulty || 2,
    unlockTest: base.unlockTest || `Perform ${base.name || titleFromId(requestedId)} with control on both sides.`,
    masteryTest: base.masteryTest || `Use ${base.name || titleFromId(requestedId)} in flow without hesitation.`,
    sourceUrl: base.sourceUrl || null,
    tutorialUrl: base.tutorialUrl || null,
    videoUrl: base.videoUrl || null,
    notes: base.notes || "",
  };

  const instructions = buildMovementInstructions(normalized);
  return {
    ...normalized,
    instructions,
    profile: {
      overview: normalized.notes || `${normalized.name} belongs to the ${normalized.tree} movement path.`,
      practiceInstructions: instructions,
      coachingCues: [
        "Move slowly enough that balance stays honest.",
        "Keep the exit as intentional as the entry.",
        "Repeat on both sides before adding speed.",
      ],
      safetyNotes: [
        "Stop if there is sharp pain.",
        "Use a clear floor and scale range before intensity.",
      ],
      ...(normalized.profile || {}),
    },
  };
};

